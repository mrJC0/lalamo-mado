#!/usr/bin/env pwsh
# Deploys the working tree as the dev build of edit-md (plan 19), beside the released one and never touching it:
#   <claude home>/bin/edit-md-dev/              the binary, built with -Channel dev
#   <claude home>/edit-md-dev/                  the reviewer's own files for the dev build
#   <repo>/.claude/skills/edit-md-dev/SKILL.md  /edit-md-dev, generated from onboarding/skills/edit-md/SKILL.md; git-ignored
# The first deploy copies the released build's labels, send buttons, glossary and settings once; -Reseed copies them again.
param(
    [string]$ClaudeHome = ($env:CLAUDE_CONFIG_DIR ? $env:CLAUDE_CONFIG_DIR : (Join-Path $HOME '.claude')),
    [string]$Rid = [System.Runtime.InteropServices.RuntimeInformation]::RuntimeIdentifier,
    [switch]$Reseed
)
$ErrorActionPreference = 'Stop'
$repo = Resolve-Path (Join-Path $PSScriptRoot '..')
$toolHome = Join-Path $ClaudeHome 'bin' 'edit-md-dev'
$userFiles = Join-Path $ClaudeHome 'edit-md-dev'
$releasedToolHome = Join-Path $ClaudeHome 'bin' 'edit-md'
$releasedUserFiles = Join-Path $ClaudeHome 'edit-md'
$firstDeploy = -not (Test-Path $toolHome)

& (Join-Path $PSScriptRoot 'publish.ps1') -Rid $Rid -Out $toolHome -Channel dev
if ($LASTEXITCODE) { exit $LASTEXITCODE }

$seeded = @()
if ($firstDeploy -or $Reseed) {
    New-Item -ItemType Directory -Force $userFiles | Out-Null
    $seeds = @('comment_labels.json', 'send_buttons.json', 'glossary.json' | ForEach-Object { @{ From = Join-Path $releasedUserFiles $_; To = Join-Path $userFiles $_ } }) +
        @{ From = Join-Path $releasedToolHome 'prefs.json'; To = Join-Path $toolHome 'prefs.json' }
    foreach ($seed in $seeds | Where-Object { Test-Path $_.From }) {
        Copy-Item $seed.From $seed.To -Force
        $seeded += $seed.To
    }
}

$exe = Join-Path $toolHome ($IsWindows ? 'edit-md.exe' : 'edit-md')
$build = (& $exe help | Select-Object -Last 1).Trim()

$usesDefaultClaudeHome = [IO.Path]::GetFullPath($ClaudeHome) -eq [IO.Path]::GetFullPath((Join-Path $HOME '.claude'))
$forwardSlashes = { param($path) [IO.Path]::GetFullPath($path).Replace('\', '/') }
$binaryPath = $usesDefaultClaudeHome ? '$HOME/.claude/bin/edit-md-dev/' : "$(& $forwardSlashes $toolHome)/"
$toolHomeTilde = $usesDefaultClaudeHome ? '~/.claude/bin/edit-md-dev/' : "$(& $forwardSlashes $toolHome)/"
$userFilesTilde = $usesDefaultClaudeHome ? '~/.claude/edit-md-dev/' : "$(& $forwardSlashes $userFiles)/"

$skill = (Get-Content (Join-Path $repo 'onboarding' 'skills' 'edit-md' 'SKILL.md') -Raw).
    Replace('$HOME/.claude/bin/edit-md/', $binaryPath).
    Replace('~/.claude/bin/edit-md/', $toolHomeTilde).
    Replace('~/.claude/edit-md/', $userFilesTilde).
    Replace('skills --ran edit-md ', 'skills --ran edit-md-dev ')
$skill = $skill -replace '(?m)^name: edit-md$', 'name: edit-md-dev'
$skill = $skill -replace '(?m)^description: .*$', 'description: The dev build of edit-md, deployed from this repo''s working tree — review a Markdown file in the browser with the agent in the loop, to try what is being built. Use when the user runs /edit-md-dev [path].'
$skill = $skill -replace '(?m)^Missing binary → .*$', 'Missing binary → run `pwsh scripts/deploy-dev.ps1` in this repo.'
$devBuildBanner = @"

> **The dev build of edit-md** — $build, deployed $(Get-Date -Format 'yyyy-MM-dd HH:mm') from this repo's working tree.
> Generated by ``scripts/deploy-dev.ps1`` from ``onboarding/skills/edit-md/SKILL.md``: change that file, never this one.
> If ``src/`` or that SKILL.md changed since, run ``pwsh scripts/deploy-dev.ps1`` before ``serve``: it stops only the dev server and its ``wait``s, so then ``serve`` again, re-``open`` each doc and re-arm its ``wait``.
> ``/edit-md`` drives the released build; both can run in one session, each with its own server and browser window.
"@
$skill = $skill -replace '(?s)^(---\r?\n.*?\r?\n---\r?\n)', "`$1$($devBuildBanner.Replace('$', '$$'))`n"

$skillTarget = Join-Path $repo '.claude' 'skills' 'edit-md-dev'
New-Item -ItemType Directory -Force $skillTarget | Out-Null
Set-Content -Path (Join-Path $skillTarget 'SKILL.md') -Value $skill -NoNewline -Encoding utf8NoBOM

[pscustomobject]@{
    binary    = $exe
    build     = $build
    userFiles = $userFiles
    seeded    = $seeded
    skill     = Join-Path $skillTarget 'SKILL.md'
} | ConvertTo-Json
